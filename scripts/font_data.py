def _rows_to_bytes(rows, height):
    """Convert a list of '.'/'#' strings into a list of bytes, MSB leftmost."""
    if len(rows) != height:
        raise ValueError(f"expected {height} rows, got {len(rows)}")
    out = []
    for r in rows:
        if len(r) != GLYPH_WIDTH:
            raise ValueError(f"expected {GLYPH_WIDTH} columns, got {len(r)!r}")
        v = 0
        for col, ch in enumerate(r):
            if ch == "#":
                v |= 1 << (GLYPH_WIDTH - 1 - col)
            elif ch != ".":
                raise ValueError(f"unexpected pixel character {ch!r}")
        out.append(v)
    return out


def bank(height):
    """Return a list of GLYPH_COUNT lists of `height` bytes, unpopulated glyphs blank."""
    src = FONT16 if height == 16 else FONT8
    return [_rows_to_bytes(src[c], height) if c in src else [0] * height
            for c in range(GLYPH_COUNT)]


def glyph_rows(code, height):
    """Byte rows for one glyph. Codes at or above GLYPH_COUNT render blank."""
    if code >= GLYPH_COUNT:
        return [0] * height
    src = FONT16 if height == 16 else FONT8
    if code not in src:
        return [0] * height
    return _rows_to_bytes(src[code], height)
