"""Hand authored glyph bitmaps for vga_text_engine.

Two independent fonts, one per glyph height, so that switching CTRL.FONT_H16 picks a
design drawn for that cell rather than a scaled version of the other one.

  FONT8   8 wide by 8 tall.  Body columns 0-5 (7 for M, W and the block glyphs),
          body rows 0-6, row 7 left clear for line spacing. Descenders use row 7.

  FONT16  8 wide by 16 tall. Body columns 0-6. Rows 0-1 clear, cap height rows 2-12
          with the baseline on row 12, x-height rows 6-12, descenders rows 13-14,
          row 15 clear.

Both fonts use two pixel stems so they stay legible after the RGB444 palette is
expanded to a narrow DAC.

Codes 0x00-0x0F hold block, shade and box drawing glyphs. The box pieces put the
horizontal rule on the vertical centre rows (3-4 at 8 tall, 7-8 at 16 tall) and the
vertical rule on columns 3-4, so frames join up in either height.

Codes 0x10-0x1F are unused and render blank. Codes 0x20-0x7E are printable ASCII.
Codes 0x7F and above render blank; the hardware detects them from bit 7 of the
character code and never reaches the ROM.

'#' is an lit pixel, '.' is clear. This module is the single source of truth: it
feeds both the generated SystemVerilog ROM and the Python reference renderer.
"""

